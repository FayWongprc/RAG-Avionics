# ── 固定规则层：原子需求分解黄金准则 ─────────────────────

ATOMIC_REQ_GOLDEN_RULES = """
一条合格的"原子需求"必须同时满足以下特性：

1. 单一性 (Singularity)
   一条需求只表达一个可独立验证的约束或行为。
   若一句话中出现"并且/同时/以及"连接两个不同动作或条件，应拆为多条。

2. 无歧义性 (Unambiguity)
   不使用"适当的""合理的""尽快"等模糊词汇。
   所有阈值、时限、状态必须有明确的数值或枚举定义。

3. 可测试性 (Testability)
   每条需求必须能设计出至少一个测试用例来判定通过/失败。
   需求中必须包含可观测的输入条件和期望输出/行为。

4. 可追溯性 (Traceability)
   每条原子需求必须能追溯到原始需求编号和来源文本。

5. 完整性 (Completeness)
   关键约束不能遗漏：触发条件、禁止条件、时序约束、告警行为、边界值。

6. 一致性 (Consistency)
   原子需求之间不能相互矛盾。
""".strip()


